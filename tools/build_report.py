def find_font(filename):
    """Finds a font file by name in the usual Linux font directories (Fedora and Debian layouts differ)."""
    for d in FONT_DIRS:
        for dirpath, _, files in os.walk(d):
            if filename in files:
                return os.path.join(dirpath, filename)
    sys.exit(f"font {filename} not found: install liberation-serif-fonts and dejavu-sans-fonts "
             f"(dejavu-sans-mono-fonts)")


